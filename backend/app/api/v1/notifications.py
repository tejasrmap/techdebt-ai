from typing import Optional, List, Dict, Any
from fastapi import APIRouter, Depends, HTTPException, status
from pydantic import BaseModel
from sqlalchemy.orm import Session

from app.database import get_db
from app.models.all_models import User, Notification, NotificationPreference
from app.services.auth_service import get_current_user
from app.services.notification_service import NotificationService

router = APIRouter(prefix="/notifications", tags=["Notifications & Alerts"])

class UpdateNotificationPreferencesRequest(BaseModel):
    email_assessment_completed: Optional[bool] = None
    email_critical_risk: Optional[bool] = None
    email_billing_alerts: Optional[bool] = None
    email_weekly_digest: Optional[bool] = None
    inapp_notifications: Optional[bool] = None

class TestAlertRequest(BaseModel):
    channel: str = "in_app"  # in_app, email, both
    title: str = "Test Notification Alert"
    message: str = "This is a test notification generated by TechDebt AI."
    severity: str = "info"

@router.get("")
def list_notifications(
    unread_only: bool = False,
    limit: int = 50,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Retrieve notifications for the authenticated user and organization."""
    return NotificationService.get_user_notifications(
        db=db,
        user_id=current_user.id,
        org_id=current_user.org_id,
        limit=limit,
        unread_only=unread_only
    )

@router.get("/unread-count")
def get_unread_notification_count(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Retrieve total number of unread notifications for the user."""
    count = NotificationService.get_unread_count(
        db=db,
        org_id=current_user.org_id,
        user_id=current_user.id
    )
    return {"unread_count": count}

@router.post("/{notification_id}/read")
def mark_notification_read(
    notification_id: str,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Mark a specific notification as read."""
    success = NotificationService.mark_as_read(
        db=db,
        notification_id=notification_id,
        org_id=current_user.org_id,
        user_id=current_user.id
    )
    if not success:
        raise HTTPException(status_code=404, detail="Notification not found")
    return {"message": "Notification marked as read"}

@router.post("/read-all")
def mark_all_notifications_read(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Mark all unread notifications for the current user as read."""
    count = NotificationService.mark_all_as_read(
        db=db,
        org_id=current_user.org_id,
        user_id=current_user.id
    )
    return {"message": f"Marked {count} notifications as read", "count": count}

@router.get("/preferences")
def get_notification_preferences(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Retrieve current user's email and in-app notification preferences."""
    pref = NotificationService.get_or_create_preferences(db, current_user.id)
    return {
        "user_id": pref.user_id,
        "email_assessment_completed": pref.email_assessment_completed,
        "email_critical_risk": pref.email_critical_risk,
        "email_billing_alerts": pref.email_billing_alerts,
        "email_weekly_digest": pref.email_weekly_digest,
        "inapp_notifications": pref.inapp_notifications,
        "updated_at": pref.updated_at
    }

@router.put("/preferences")
def update_notification_preferences(
    req: UpdateNotificationPreferencesRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Update user's notification preferences."""
    updates = req.model_dump(exclude_unset=True)
    pref = NotificationService.update_preferences(db, current_user.id, updates)
    return {
        "message": "Notification preferences updated successfully",
        "preferences": {
            "email_assessment_completed": pref.email_assessment_completed,
            "email_critical_risk": pref.email_critical_risk,
            "email_billing_alerts": pref.email_billing_alerts,
            "email_weekly_digest": pref.email_weekly_digest,
            "inapp_notifications": pref.inapp_notifications,
            "updated_at": pref.updated_at
        }
    }

@router.post("/test-alert")
def send_test_alert(
    req: TestAlertRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Trigger a test notification to verify delivery channels."""
    notif = NotificationService.create_notification(
        db=db,
        org_id=current_user.org_id,
        user_id=current_user.id,
        title=req.title,
        message=req.message,
        category="system",
        severity=req.severity
    )

    email_sent = False
    if req.channel in ("email", "both") and current_user.email:
        email_sent = NotificationService.dispatch_email(
            to_email=current_user.email,
            subject=f"[TechDebt AI Test Alert] {req.title}",
            html_body=f"<p>{req.message}</p>"
        )

    return {
        "message": "Test notification created",
        "notification_id": notif.id,
        "email_dispatched": email_sent
    }
